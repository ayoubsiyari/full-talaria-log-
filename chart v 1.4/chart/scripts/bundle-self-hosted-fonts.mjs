#!/usr/bin/env node
/**
 * Download Google Fonts as local woff2 + generate /chart/fonts/talaria-fonts.css
 * Run: node "chart v 1.4/chart/scripts/bundle-self-hosted-fonts.mjs"
 */
import fs from "fs";
import path from "path";
import { createHash } from "crypto";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const FONTS_ROOT = path.resolve(__dirname, "../fonts");
const WOFF2_DIR = path.join(FONTS_ROOT, "woff2");
const CSS_OUT = path.join(FONTS_ROOT, "talaria-fonts.css");

const FONT_SPECS = [
  "DM+Sans:ital,wght@0,400;0,500;0,600;0,700;1,400",
  "Exo+2:wght@400;500;600;700;800;900",
  "JetBrains+Mono:wght@400;500;600;700",
  "Roboto:wght@400;500;700",
  "Zain:wght@200;300;400;700;800;900",
  "Plus+Jakarta+Sans:wght@300;400;500;600;700",
];

const WOFF2_UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";

async function fetchCss(spec) {
  const url = `https://fonts.googleapis.com/css2?family=${spec}&display=swap`;
  const res = await fetch(url, { headers: { "User-Agent": WOFF2_UA } });
  if (!res.ok) throw new Error(`Font CSS fetch failed ${res.status}: ${url}`);
  return res.text();
}

function parseFontFaceBlocks(css) {
  const blocks = [];
  const re = /@font-face\s*\{([^}]+)\}/g;
  let m;
  while ((m = re.exec(css))) {
    blocks.push(m[1].trim());
  }
  return blocks;
}

function localName(remoteUrl) {
  const base = path.basename(new URL(remoteUrl).pathname);
  if (base.endsWith(".woff2")) return base;
  const hash = createHash("sha1").update(remoteUrl).digest("hex").slice(0, 12);
  return `font-${hash}.woff2`;
}

async function download(url, dest) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Download failed ${res.status}: ${url}`);
  const buf = Buffer.from(await res.arrayBuffer());
  fs.writeFileSync(dest, buf);
  return buf.length;
}

async function main() {
  fs.mkdirSync(WOFF2_DIR, { recursive: true });
  const outBlocks = ["/* Self-hosted Talaria fonts — generated by bundle-self-hosted-fonts.mjs */"];

  for (const spec of FONT_SPECS) {
    const css = await fetchCss(spec);
    for (const body of parseFontFaceBlocks(css)) {
      const srcMatch = /url\((https:[^)]+)\)\s*format\(['"]woff2['"]\)/i.exec(body);
      if (!srcMatch) continue;
      const remote = srcMatch[1];
      const file = localName(remote);
      const dest = path.join(WOFF2_DIR, file);
      if (!fs.existsSync(dest)) {
        const bytes = await download(remote, dest);
        console.log(`  + ${file} (${bytes} bytes)`);
      }
      const rewritten = body.replace(
        /url\((https:[^)]+)\)/i,
        `url('./woff2/${file}')`
      );
      outBlocks.push(`@font-face{${rewritten}}`);
    }
  }

  fs.writeFileSync(CSS_OUT, outBlocks.join("\n") + "\n");
  console.log(`Wrote ${CSS_OUT} (${outBlocks.length - 1} @font-face blocks)`);

  const mirror = path.resolve(__dirname, "../../../homepage/public/chart/fonts");
  if (fs.existsSync(path.resolve(__dirname, "../../../homepage/public/chart"))) {
    fs.mkdirSync(mirror, { recursive: true });
    fs.cpSync(FONTS_ROOT, mirror, { recursive: true });
    console.log(`Mirrored → ${mirror}`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
